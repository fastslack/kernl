export interface LoadedPolicy {
  policy: WorkspacePolicy;
  source: "file" | "default";
}

/** Read .evolve/policy.json. Returns null when missing or malformed. */
export async function loadPolicy(workspaceDir: string): Promise<WorkspacePolicy | null> {
  const path = resolve(workspaceDir, POLICY_RELPATH);
  let raw: string;
  try {
    raw = await readFile(path, "utf8");
  } catch {
    return null;
  }
  try {
    const parsed = JSON.parse(raw);
    return validatePolicy(parsed);
  } catch {
    return null;
  }
}

/** Strict shape check. Returns null on any structural mismatch. */
export function validatePolicy(input: unknown): WorkspacePolicy | null {
  if (!input || typeof input !== "object") return null;
  const o = input as Record<string, unknown>;
  if (o.version !== 1) return null;
  if (!Array.isArray(o.mutable_globs) || !o.mutable_globs.every((g) => typeof g === "string")) return null;
  if (!Array.isArray(o.protected_globs) || !o.protected_globs.every((g) => typeof g === "string")) return null;
  const ev = o.evaluation as Record<string, unknown> | undefined;
  if (!ev || typeof ev !== "object") return null;
  if (typeof ev.command !== "string" || ev.command.trim() === "") return null;
  if (typeof ev.timeout_s !== "number" || ev.timeout_s <= 0 || ev.timeout_s > 3600) return null;
  if (ev.cwd != null && typeof ev.cwd !== "string") return null;

  const out: WorkspacePolicy = {
    version: 1,
    mutable_globs: o.mutable_globs as string[],
    protected_globs: o.protected_globs as string[],
    evaluation: {
      command: ev.command,
      timeout_s: ev.timeout_s,
      cwd: typeof ev.cwd === "string" ? ev.cwd : undefined,
    },
  };
  if (o.budget && typeof o.budget === "object") {
    const b = o.budget as Record<string, unknown>;
    out.budget = {};
    if (typeof b.commit_margin === "number") out.budget.commit_margin = b.commit_margin;
    if (typeof b.max_iterations_per_cycle === "number") out.budget.max_iterations_per_cycle = b.max_iterations_per_cycle;
  }
  if (o.constraints && typeof o.constraints === "object") {
    const c = o.constraints as Record<string, unknown>;
    out.constraints = {};
    if (typeof c.max_files_changed_per_run === "number") out.constraints.max_files_changed_per_run = c.max_files_changed_per_run;
    if (Array.isArray(c.forbidden_packages) && c.forbidden_packages.every((p) => typeof p === "string")) {
      out.constraints.forbidden_packages = c.forbidden_packages as string[];
    }
  }
  return out;
}

export interface InitResult {
  policyPath: string;
  objectivesPath: string;
  checksPath: string;
  policyCreated: boolean;
  objectivesCreated: boolean;
  checksCreated: boolean;
}

/**
 * Scaffold the three files in a workspace if they don't exist.
 * Idempotent: re-running never overwrites existing content. Returns flags
 * so the caller can tell what was actually written.
 */
export async function initEvolutionFiles(
  workspaceDir: string,
  platform: NodeJS.Platform = process.platform,
): Promise<InitResult> {
  // On Windows the evaluator runs the check through cmd.exe, which cannot
  // execute run-all.sh — seed a .cmd and point the policy at it instead.
  const windows = platform === "win32";
  const policyPath = resolve(workspaceDir, POLICY_RELPATH);
  const objectivesPath = resolve(workspaceDir, OBJECTIVES_RELPATH);
  const checksPath = resolve(workspaceDir, windows ? CHECKS_RELPATH_WIN : CHECKS_RELPATH);

  await mkdir(resolve(workspaceDir, ".evolve/checks"), { recursive: true });

  const policyCreated = await writeIfMissing(policyPath, JSON.stringify(defaultPolicyFor(platform), null, 2) + "\n");
  const objectivesCreated = await writeIfMissing(objectivesPath, DEFAULT_OBJECTIVES_MD);
  const checksCreated = windows
    ? await writeIfMissing(checksPath, DEFAULT_CHECKS_CMD)
    : await writeIfMissing(checksPath, DEFAULT_CHECKS_SH, 0o755);

  return { policyPath, objectivesPath, checksPath, policyCreated, objectivesCreated, checksCreated };
}

async function writeIfMissing(path: string, content: string, mode?: number): Promise<boolean> {
  try {
    await readFile(path, "utf8");
    return false;
  } catch {
    await writeFile(path, content, { encoding: "utf8" });
    if (mode !== undefined) await chmod(path, mode);
    return true;
  }
}

/**
 * Decide whether a path inside the workspace is allowed to be mutated. A path
 * is allowed iff it is NOT globally protected, NOT in the project's
 * protected_globs, and (if mutable_globs is non-empty) matches mutable_globs.
 *
 * Globs supported: very small subset — `**` for any-depth, `*` for one
 * segment. No bracket expansion, no negation. We intentionally keep this
 * minimal to avoid a glob lib; the policy file documents what's supported.
 */
export function isPathMutable(relPath: string, policy: WorkspacePolicy): { allowed: boolean; reason?: string } {
  if (checkProtected(relPath)) {
    return { allowed: false, reason: "global protected-files rule" };
  }
  for (const g of policy.protected_globs) {
    if (matchSimpleGlob(relPath, g)) {
      return { allowed: false, reason: `policy.protected_globs matched "${g}"` };
    }
  }
  if (policy.mutable_globs.length === 0) return { allowed: true };
  for (const g of policy.mutable_globs) {
    if (matchSimpleGlob(relPath, g)) return { allowed: true };
  }
  return { allowed: false, reason: "not in policy.mutable_globs" };
}

/**
 * Tiny glob matcher with bash-globstar semantics.
 *  - `**` (with optional trailing `/`) matches zero or more path segments —
 *    so `src/** /*.ts` (no space) matches both `src/foo.ts` and `src/a/b/foo.ts`.
 *  - `*` matches one segment (no slashes).
 *  - All other chars are literal. No brackets, no negation.
 */
export function matchSimpleGlob(path: string, pattern: string): boolean {
  const escaped = pattern.replace(/[.+^$(){}|[\]\\]/g, "\\$&");
  const final = escaped
    .replace(/\*\*\//g, "__DSDIR__")
    .replace(/\*\*/g, "__DS__")
    .replace(/\*/g, "[^/]*")
    .replace(/__DSDIR__/g, "(?:.*/)?")
    .replace(/__DS__/g, ".*");
  return new RegExp("^" + final + "$").test(path);
}
