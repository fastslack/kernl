/**
 * Policy file loader for `data/workspaces/{id}/.evolve/policy.json`.
 *
 * The policy is stored as JSON (not YAML) to avoid pulling in a parser dep —
 * the kernel runs on stock Node and uses zero YAML elsewhere in tree.
 */

import { readFile, writeFile, mkdir, chmod } from "node:fs/promises";
import { resolve } from "node:path";
import { checkProtected } from "../../../../../../src/core/protected-files.js";
import type { WorkspacePolicy } from "./types.js";

export const POLICY_RELPATH = ".evolve/policy.json";
export const OBJECTIVES_RELPATH = "EVOLUTION.md";
export const CHECKS_RELPATH = ".evolve/checks/run-all.sh";
/** Windows runs the check through cmd.exe, which cannot execute a .sh file. */
export const CHECKS_RELPATH_WIN = ".evolve/checks/run-all.cmd";

/** Default policy seeded by `init`. Conservative: nothing mutable until the
 *  user decides what's safe to touch. */
export const DEFAULT_POLICY: WorkspacePolicy = {
  version: 1,
  mutable_globs: [],
  protected_globs: [],
  evaluation: {
    command: "./.evolve/checks/run-all.sh",
    timeout_s: 300,
  },
  budget: {
    commit_margin: 1.5,
    max_iterations_per_cycle: 3,
  },
};

/** The default policy for the platform the kernel runs on: on Windows the
 *  check is a .cmd script, run by cmd.exe from the workspace root. */
export function defaultPolicyFor(platform: NodeJS.Platform = process.platform): WorkspacePolicy {
  if (platform !== "win32") return DEFAULT_POLICY;
  return {
    ...DEFAULT_POLICY,
    evaluation: { ...DEFAULT_POLICY.evaluation, command: ".evolve\\checks\\run-all.cmd" },
  };
}

